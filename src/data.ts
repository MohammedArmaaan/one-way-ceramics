function buildProducts(): Product[] {
  const out: Product[] = [];
  let id = 1;
  for (const cat of PRODUCT_CATEGORIES) {
    const names = PRODUCT_NAMES[cat];
    names.forEach((name, i) => {
      out.push({
        id: `p${id++}`,
        name,
        category: cat,
        collection: COLLECTIONS_LIST[(i + id) % COLLECTIONS_LIST.length],
        price: `₹${Math.floor(120 + (id * 13) % 1800)}`,
        size: SIZES[i % SIZES.length],
        finish: FINISHES[(i + id) % FINISHES.length],
        image: PRODUCT_IMAGES[(i + id) % PRODUCT_IMAGES.length],
        badge: i === 0 ? 'New' : i === 3 ? 'Best Seller' : i === 7 ? 'Trending' : undefined,
      });
    });
  }
  return out;
}

